export const TIME_RANGE_OPTIONS = [
  { label: 'Last 24h', value: '24h' },
  { label: 'Last 7d', value: '7d' },
  { label: 'Last 30d', value: '30d' },
]

const RANGE_TO_MS = {
  '24h': 24 * 60 * 60 * 1000,
  '7d': 7 * 24 * 60 * 60 * 1000,
  '30d': 30 * 24 * 60 * 60 * 1000,
}

export function resolveRangeMs(rangeValue) {
  return RANGE_TO_MS[rangeValue] || RANGE_TO_MS['24h']
}
